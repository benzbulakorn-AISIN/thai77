// Geocode demo places with OpenStreetMap Nominatim and generate supabase/seed_places.sql
// Runs in GitHub Actions (needs internet). Respects Nominatim policy: 1 request/sec, real User-Agent.
//
// For every place in data/seed/places/*.json:
//   1. search Nominatim inside the province bounding box
//   2. accept only a result whose point is INSIDE the province polygon (public/geo/provinces.geojson)
//   3. find the district by point-in-polygon (public/geo/districts/<pcode>.geojson)
//   4. keep OSM tags that are sourced: opening_hours, phone, website
// Places that cannot be verified are still inserted, but without coordinates (shown as "รอตรวจสอบ").
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const SEED_DIR = 'data/seed/places';
const GEO = 'public/geo';
const UA = `thai77-trip-planner/0.4 (+https://github.com/${process.env.GITHUB_REPOSITORY || 'local'})`;
const TODAY = new Date().toISOString().slice(0, 10);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// ---------- geometry ----------
function inRing(x, y, ring) {
  let c = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
}
function inPolygon(x, y, poly) {
  if (!inRing(x, y, poly[0])) return false;
  for (let k = 1; k < poly.length; k++) if (inRing(x, y, poly[k])) return false; // hole
  return true;
}
function inGeometry(x, y, g) {
  if (g.type === 'Polygon') return inPolygon(x, y, g.coordinates);
  if (g.type === 'MultiPolygon') return g.coordinates.some((p) => inPolygon(x, y, p));
  return false;
}
function bbox(g) {
  let a = 180, b = 90, c = -180, d = -90;
  const v = (q) => (typeof q[0] === 'number'
    ? (a = Math.min(a, q[0]), c = Math.max(c, q[0]), b = Math.min(b, q[1]), d = Math.max(d, q[1]))
    : q.forEach(v));
  v(g.coordinates);
  return { minX: a - 0.02, minY: b - 0.02, maxX: c + 0.02, maxY: d + 0.02 };
}

// deterministic UUID from key (so re-running updates the same rows)
function uuidFrom(key) {
  const h = crypto.createHash('sha1').update(`thai77:place:${key}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-${((parseInt(h[16], 16) & 3) | 8).toString(16)}${h.slice(17, 20)}-${h.slice(20, 32)}`;
}
const sq = (s) => (s === null || s === undefined || s === '' ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const httpUrl = (u) => (typeof u === 'string' && /^https?:\/\/[^\s]+$/i.test(u.trim()) ? u.trim() : null);

// ---------- nominatim ----------
let last = 0;
async function search(q, box) {
  const wait = 1100 - (Date.now() - last);
  if (wait > 0) await sleep(wait);
  last = Date.now();
  const u = new URL('https://nominatim.openstreetmap.org/search');
  u.search = new URLSearchParams({
    q, format: 'jsonv2', limit: '8', countrycodes: 'th', bounded: '1', extratags: '1',
    'accept-language': 'th', viewbox: `${box.minX},${box.maxY},${box.maxX},${box.minY}`,
  }).toString();
  const r = await fetch(u, { headers: { 'User-Agent': UA } });
  if (!r.ok) throw new Error(`Nominatim ${r.status}`);
  return r.json();
}

// ---------- main ----------
const provinces = JSON.parse(fs.readFileSync(`${GEO}/provinces.geojson`, 'utf8'));
const files = fs.readdirSync(SEED_DIR).filter((f) => f.endsWith('.json')).sort();
const sql = [];
const report = [];
let ok = 0, miss = 0;

sql.push(`-- GENERATED by scripts/build-places.mjs on ${TODAY}`);
sql.push('-- Demo Data. Coordinates/district/contact from OpenStreetMap (ODbL) via Nominatim.');
sql.push('-- Opening hours, fees and other details are NOT verified -> verification = pending.');
sql.push('-- Safe to run more than once.\n');
sql.push('begin;');

for (const file of files) {
  const seed = JSON.parse(fs.readFileSync(path.join(SEED_DIR, file), 'utf8'));
  const prov = provinces.features.find((f) => f.properties.pcode === seed.province_pcode);
  if (!prov) throw new Error(`${file}: province ${seed.province_pcode} not in provinces.geojson`);
  if (prov.properties.name_th.replace(/^จังหวัด/, '') !== seed.province_th) {
    throw new Error(`${file}: pcode ${seed.province_pcode} is ${prov.properties.name_th}, expected ${seed.province_th}`);
  }
  const districts = JSON.parse(fs.readFileSync(`${GEO}/districts/${seed.province_pcode}.geojson`, 'utf8')).features;
  const box = bbox(prov.geometry);
  report.push(`\n## ${seed.province_th} (${seed.province_pcode})\n`);

  for (const p of seed.places) {
    const id = uuidFrom(p.key);
    let hit = null;
    for (const q of [p.osm_query, p.name_th, p.name_en && `${p.name_en}, ${seed.province_th}`].filter(Boolean)) {
      try {
        const res = await search(q, box);
        hit = res.find((r) => inGeometry(+r.lon, +r.lat, prov.geometry));
      } catch (e) {
        console.warn(`  ! ${q}: ${e.message}`);
      }
      if (hit) break;
    }

    let lat = null, lng = null, district = null, osmUrl = null, tags = {};
    if (hit) {
      lat = (+hit.lat).toFixed(6);
      lng = (+hit.lon).toFixed(6);
      district = districts.find((d) => inGeometry(+hit.lon, +hit.lat, d.geometry))?.properties.pcode ?? null;
      osmUrl = `https://www.openstreetmap.org/${hit.osm_type}/${hit.osm_id}`;
      tags = hit.extratags || {};
      ok++;
      report.push(`- ✅ ${p.name_th} → ${lat}, ${lng} · ${district ?? 'ไม่พบอำเภอ'} · ${osmUrl} (OSM: ${hit.display_name.split(',')[0]})`);
    } else {
      miss++;
      report.push(`- ⚠️ ${p.name_th} — ไม่พบใน OSM ภายในจังหวัด (ต้องใส่พิกัดเองในหน้า Admin)`);
    }
    console.log(`${hit ? 'OK ' : 'MISS'} ${p.name_th}`);

    const hours = typeof tags.opening_hours === 'string' ? tags.opening_hours.slice(0, 200) : null;
    const phone = typeof (tags.phone || tags['contact:phone']) === 'string' ? (tags.phone || tags['contact:phone']).slice(0, 60) : null;
    const website = httpUrl(tags.website || tags['contact:website']);

    sql.push(`
insert into public.places (id, name_th, name_en, province_id, district_id, category_id, short_description,
  lat, lng, opening_hours_text, phone, website_url, verification, is_demo, is_published)
values (${sq(id)}, ${sq(p.name_th)}, ${sq(p.name_en)},
  (select id from public.provinces where pcode = ${sq(seed.province_pcode)}),
  (select id from public.districts where pcode = ${sq(district)}),
  (select id from public.categories where slug = ${sq(p.category)}),
  ${sq(p.short_description)}, ${lat ?? 'null'}, ${lng ?? 'null'}, ${sq(hours)}, ${sq(phone)}, ${sq(website)},
  'pending', true, true)
on conflict (id) do update set
  name_th = excluded.name_th, name_en = excluded.name_en, province_id = excluded.province_id,
  district_id = coalesce(excluded.district_id, places.district_id),
  category_id = excluded.category_id, short_description = excluded.short_description,
  lat = coalesce(excluded.lat, places.lat), lng = coalesce(excluded.lng, places.lng),
  opening_hours_text = coalesce(excluded.opening_hours_text, places.opening_hours_text),
  phone = coalesce(excluded.phone, places.phone), website_url = coalesce(excluded.website_url, places.website_url);`);

    sql.push(`delete from public.place_sources where place_id = ${sq(id)} and source_type = 'osm';`);
    if (osmUrl) {
      const fields = ['lat', 'lng', 'district_id', hours && 'opening_hours_text', phone && 'phone', website && 'website_url'].filter(Boolean);
      sql.push(`insert into public.place_sources (place_id, source_url, source_name, source_type, fields, checked_at)
values (${sq(id)}, ${sq(osmUrl)}, 'OpenStreetMap contributors (ODbL)', 'osm', array[${fields.map(sq).join(',')}]::text[], ${sq(TODAY)});`);
    }
  }
}

sql.push('\ncommit;\n');
sql.push(`-- check: expect ${ok + miss} demo places`);
sql.push('select p.name_th as province, count(*) as places, count(pl.lat) as with_coords');
sql.push('from public.places pl join public.provinces p on p.id = pl.province_id');
sql.push('where pl.is_demo group by p.name_th order by p.name_th;');

fs.mkdirSync('supabase', { recursive: true });
fs.writeFileSync('supabase/seed_places.sql', sql.join('\n'));
fs.writeFileSync('data/seed/places-report.md',
  `# Place seed report (${TODAY})\n\nพบพิกัด ${ok} แห่ง · ไม่พบ ${miss} แห่ง\n` +
  'ข้อมูลพิกัดจาก © OpenStreetMap contributors (ODbL)\n' + report.join('\n') + '\n');
console.log(`\nDone: ${ok} geocoded, ${miss} missing`);
